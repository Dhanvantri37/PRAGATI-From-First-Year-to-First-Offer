# MODEL 3 — SKILL GAP SCORE + ELIGIBILITY PREDICTOR
# Dataset: LinkedIn Job Postings (Kaggle → arshkon/linkedin-job-postings)
#          OR generated job_skills.csv
# Features: n_required, n_resume_skills, n_matched, match_ratio, experience
# Targets:  gap_score (0→1), eligibility_pct (0→100)
# ══════════════════════════════════════════════════════════════════════════════
header("MODEL 3: SKILL GAP SCORE + ELIGIBILITY PREDICTOR")
print("  Dataset: https://www.kaggle.com/datasets/arshkon/linkedin-job-postings")

# LinkedIn dataset stores job_skills.csv inside mappings/ subfolder
# Check all possible locations automatically
JOB_CSV = None
_job_candidates = [
    'skills/job_skills.csv',                           # direct (after manual copy)
    'skills/job_posting_skills.csv',                   # alternate name
    'skills/job_skills/mappings/job_skills.csv',       # LinkedIn standard structure
    'skills/mappings/job_skills.csv',                  # alternate unzip location
    'skills/postings.csv',                             # main postings file
    'skills/job_skills/postings.csv',
]
for _p in _job_candidates:
    if os.path.exists(_p):
        JOB_CSV = _p
        print(f"  Found skills dataset at: {_p}")
        break
if JOB_CSV is None:
    JOB_CSV = 'skills/job_skills.csv'

if not os.path.exists(JOB_CSV):
    print("  ⚠ Generating synthetic job skills data...")
    os.makedirs('skills', exist_ok=True)
    all_s = ['Python','Java','JavaScript','React','SQL','Git','Docker','Machine Learning',
             'TensorFlow','AWS','Linux','MongoDB','PostgreSQL','REST API','HTML','CSS',
             'TypeScript','Kubernetes','CI/CD','Pandas','NumPy','Spring Boot','Node.js']
    job_map = {
        'Software Engineer':['Python','Java','JavaScript','React','SQL','Git','Docker','REST API'],
        'Data Scientist':['Python','Machine Learning','TensorFlow','Pandas','NumPy','SQL','scikit-learn'],
        'DevOps Engineer':['Docker','Kubernetes','Jenkins','AWS','Linux','CI/CD','Terraform','Git'],
        'Frontend Developer':['React','Angular','HTML','CSS','JavaScript','TypeScript','Bootstrap'],
        'Backend Developer':['Node.js','Python','Java','Spring Boot','MongoDB','PostgreSQL','Docker'],
    }
    rows3 = []
    for title, req_skills in job_map.items():
        for _ in range(200):
            rows3.append({'job_title':title,'required_skills':','.join(np.random.choice(req_skills, np.random.randint(4,len(req_skills)), replace=False)),'experience_years':np.random.choice([0,1,2,3,5])})
    pd.DataFrame(rows3).to_csv(JOB_CSV, index=False)

df3 = pd.read_csv(JOB_CSV)
print(f"  Rows: {len(df3)}")

all_skills_vocab = ['Python','Java','JavaScript','React','Node.js','SQL','Git','Docker',
                    'Machine Learning','TensorFlow','AWS','Linux','MongoDB','PostgreSQL',
                    'REST API','HTML','CSS','TypeScript','Kubernetes','CI/CD','Pandas','NumPy']
rows3 = []
for _, row in df3.iterrows():
    req = set(str(row.get('required_skills','')).split(','))
    n_req = len(req)
    n_resume = np.random.randint(3,12)
    resume_s = set(np.random.choice(all_skills_vocab, n_resume, replace=False))
    matched = len(req & resume_s)
    mr = matched / max(n_req, 1)
    rows3.append({'n_required':n_req,'n_resume_skills':n_resume,'n_matched':matched,
                  'match_ratio':round(mr,3),'experience_years':row.get('experience_years',0),
                  'gap_score':round(1-mr,3),'eligibility_pct':round(mr*100*(0.9+0.1*np.random.random()),1)})

feat_df = pd.DataFrame(rows3)
GAP_FEATURES = ['n_required','n_resume_skills','n_matched','match_ratio','experience_years']
Xg = feat_df[GAP_FEATURES]

# Gap score regressor
Xgtr, Xgte, yg_tr, yg_te = train_test_split(Xg, feat_df['gap_score'], test_size=0.2, random_state=42)
gap_candidates = {
    'RandomForest':     Pipeline([('sc',StandardScaler()),('m',RandomForestRegressor(n_estimators=100,random_state=42))]),
    'GradientBoosting': Pipeline([('sc',StandardScaler()),('m',GradientBoostingRegressor(n_estimators=100,random_state=42))]),
    'Ridge':            Pipeline([('sc',StandardScaler()),('m',Ridge(alpha=1.0))]),
}
best_gap, best_gap_name = None, ''
best_r2 = -999
for name, pipe in gap_candidates.items():
    cv_r2 = cross_val_score(pipe, Xg, feat_df['gap_score'], cv=5, scoring='r2').mean()
    pipe.fit(Xgtr, yg_tr)
    r2 = r2_score(yg_te, pipe.predict(Xgte))
    mae = mean_absolute_error(yg_te, pipe.predict(Xgte))
    print(f"  GAP  {name:22s}: CV_R2={cv_r2:.3f} | Test_R2={r2:.3f} | MAE={mae:.4f}")
    if cv_r2 > best_r2:
        best_r2, best_gap, best_gap_name = cv_r2, pipe, name

# Eligibility regressor (same features)
_, _, ye_tr, ye_te = train_test_split(Xg, feat_df['eligibility_pct'], test_size=0.2, random_state=42)
elig_pipe = Pipeline([('sc',StandardScaler()),('m',GradientBoostingRegressor(n_estimators=100,random_state=42))])
elig_pipe.fit(Xgtr, ye_tr)
elig_r2 = r2_score(ye_te, elig_pipe.predict(Xgte))
print(f"  ELIG GradientBoosting          : Test_R2={elig_r2:.3f}")

print(f"\n  Gap Winner: {best_gap_name}")
save(best_gap,       'gap_score_model.pkl')
save(elig_pipe,      'eligibility_model.pkl')
save(GAP_FEATURES,   'gap_features.pkl')


