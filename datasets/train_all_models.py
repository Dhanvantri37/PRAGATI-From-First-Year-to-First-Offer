print(f"  Rows: {len(df4)} | Difficulties: {dict(df4.difficulty.value_counts())}")

X4, y4 = df4['combined'], df4['difficulty']
Xtr4, Xte4, ytr4, yte4 = train_test_split(X4, y4, test_size=0.2, random_state=42, stratify=y4)

apt_candidates = {
    'LinearSVC':          Pipeline([('t',TfidfVectorizer(ngram_range=(1,2),max_features=1000)),('c',LinearSVC(C=1.0,max_iter=2000))]),
    'LogisticRegression': Pipeline([('t',TfidfVectorizer(ngram_range=(1,2),max_features=1000)),('c',LogisticRegression(C=1.0,max_iter=500,random_state=42))]),
    'RandomForest':       Pipeline([('t',TfidfVectorizer(ngram_range=(1,2),max_features=1000)),('c',RandomForestClassifier(n_estimators=100,random_state=42))]),
}
best_apt, best_apt_name, best_apt_cv = None, '', 0
for name, pipe in apt_candidates.items():
    cv4 = cross_val_score(pipe, X4, y4, cv=3, scoring='accuracy').mean()
    pipe.fit(Xtr4, ytr4)
    acc = accuracy_score(yte4, pipe.predict(Xte4))
    print(f"  {name:22s}: CV_Acc={cv4:.3f} | Test_Acc={acc:.3f}")
    if cv4 > best_apt_cv:
        best_apt_cv, best_apt, best_apt_name = cv4, pipe, name

le_topic = LabelEncoder().fit(df4['topic'])
print(f"\n  Winner: {best_apt_name}")
save(best_apt,  'aptitude_difficulty_model.pkl')
save(le_topic,  'topic_encoder.pkl')


